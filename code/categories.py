"""categories.py: the irAE category scaffold and the rules that PROPOSE candidates.

Plain-language note: this file lists the immunotherapy side-effect categories
(colitis, hepatitis, ...) and, for each one, the search rules Claude used to
find candidate CTCAE terms, ICD-10-CM codes, and FDA reaction terms, plus a
SUGGESTED role and confidence for the obvious ones. Every suggestion here is a
draft. Onyekachi makes the decision on every row in the review spreadsheet
(data/curation/review_*.csv); nothing here is final.

Category list follows the organ groupings of the ASCO 2021 guideline on
management of irAEs in patients treated with immune checkpoint inhibitor
therapy (Schneider et al., J Clin Oncol 2021;39:4073-4126), with additions
where CTCAE v6.0 or the literature gives a distinct entity (vitiligo,
sarcoid-like reaction, HLH). Category list confirmed by the author 2026-10-13.

Roles
  primary     names the condition itself; enough on its own to identify it
  supporting  lab, symptom, or grade-defining term; consistent with the
              category but not specific to it
  lookalike   a different condition often confused with this one (listed so
              analysts can exclude it deliberately)
  companion   the drug-cause code that must accompany a condition code
  review      found by a search rule, no suggestion; author decides
  exclude     found by a search rule, not relevant (author marks)

Specificity (published as `specificity`; `confidence` is the author's confidence in the role)
  High      term/code names the condition and is used for it in practice
  Moderate  right organ and process, but also used for non-immune causes
  Low       supporting or non-specific

ICD-10-CM rules use codes WITHOUT the dot (K521 = K52.1). A prefix matches
the code and all its children.
"""

